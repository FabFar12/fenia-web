// Turns a production build (dist/) into a staging-only build before the CI
// uploads it to staging.fenia.com.ar (docs/ventas, step 2.1, decision D12).
//
//  - Hostinger keeps the subdomain inside production's public_html, so the
//    same files also answer at fenia.com.ar/staging/. Lock them to the staging
//    hostname (threat model C20, test S-25).
//  - Never indexable: X-Robots-Tag + a disallow-all robots.txt.
//  - Hostinger's placeholder page is denied. (Hidden files are denied by the
//    base public/.htaccess since step 3.5, after the pilot here; H-01.)
//
//   node scripts/prepare-staging.mjs [distDir]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dist = process.argv[2] ?? 'dist';
const MARKER = '# ── STAGING ONLY';

const stagingRules = `${MARKER} — generated by scripts/prepare-staging.mjs (docs/ventas C20, H-01) ──
<IfModule mod_headers.c>
  Header always set X-Robots-Tag "noindex, nofollow"
</IfModule>

# Answer only on staging.fenia.com.ar: fenia.com.ar/staging/ must not serve this copy.
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTP_HOST} !^staging\\.fenia\\.com\\.ar$ [NC]
  RewriteRule ^ - [F,L]
</IfModule>

# Hostinger's placeholder page.
<FilesMatch "^default\\.php$">
  <IfModule mod_authz_core.c>
    Require all denied
  </IfModule>
  <IfModule !mod_authz_core.c>
    Order allow,deny
    Deny from all
  </IfModule>
</FilesMatch>
# ── end STAGING ONLY ──

`;

const htaccessPath = join(dist, '.htaccess');
const htaccess = readFileSync(htaccessPath, 'utf8');
if (htaccess.includes(MARKER)) {
  console.error('prepare-staging: dist/.htaccess already has the staging block; refusing to add it twice.');
  process.exit(1);
}
writeFileSync(htaccessPath, stagingRules + htaccess);
writeFileSync(join(dist, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
console.log(`prepare-staging: ${htaccessPath} locked to staging.fenia.com.ar (noindex, placeholder denied); robots.txt disallows all.`);
